'use strict';

/**
 * Component Markdown documentation generator.
 *
 * Owns src/components/<kebab>/<kebab>.md for every component:
 *   - Figma-sourced docs (overview, text elements, installation, properties, sizes,
 *     specs, variants) written on every Figma sync.
 *   - "Figma Changelog & Diff Status" partition: diffs the incoming Figma snapshot
 *     against the previous one (stored in .figma-docs-state.json) and lists exact
 *     changes, or "Nothing changed" when the component is identical.
 *   - Local baseline docs (from <kebab>.types.ts) for components never synced from Figma.
 *
 * Docs-only: this module never writes .tsx / .types.ts / .scss / .dart files.
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = process.cwd();
const COMPONENTS_DIR = path.join(ROOT, 'src', 'components');
const STATE_FILE = path.join(ROOT, '.figma-docs-state.json');
const PACKAGE_NAME = '@d1hdfc/ui-components';
const HISTORY_LIMIT = 10;
const SYNC_BURST_MS = Number(process.env.DOCS_SYNC_BURST_MS || 10_000);

const GENERATED_MARKER = '<!-- Generated by scripts/docs-generator.cjs. Manual edits are overwritten on the next Figma sync. -->';
const LOCAL_SOURCE_MARKER = '<!-- docs-source: local -->';
const FIGMA_SOURCE_MARKER = '<!-- docs-source: figma -->';
const TIMESTAMP_PREFIX = '> Last updated: ';

// Lazily resolved to avoid a circular require with code-generator.cjs
const naming = () => require('./code-generator.cjs');

// ==========================================
// State (previous Figma snapshots + change history)
// ==========================================

function loadState() {
  try {
    if (fs.existsSync(STATE_FILE)) return JSON.parse(fs.readFileSync(STATE_FILE, 'utf8'));
  } catch {
    // corrupted state -> start fresh
  }
  return {};
}

function saveState(state) {
  fs.writeFileSync(STATE_FILE, JSON.stringify(state, null, 2), 'utf8');
}

// ==========================================
// Formatting helpers
// ==========================================

function md(value) {
  if (value === null || value === undefined || value === '') return '—';
  return String(value).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

function cleanPropName(key) {
  // Figma TEXT / BOOLEAN / INSTANCE_SWAP property keys look like "label#123:4"
  return String(key).replace(/#[^#]*$/, '');
}

function hex(color) {
  if (!color) return null;
  if (typeof color === 'string') return color.toUpperCase();
  return color.hex ? String(color.hex).toUpperCase() : null;
}

function px(value) {
  return typeof value === 'number' ? `${value}px` : null;
}

function padding(node) {
  const values = [node.paddingTop, node.paddingRight, node.paddingBottom, node.paddingLeft];
  if (values.every(v => typeof v !== 'number')) return null;
  return values.map(v => px(v) ?? '—').join(' ');
}

function parseVariantName(name) {
  const props = {};
  for (const part of String(name || '').split(',')) {
    const eq = part.indexOf('=');
    if (eq > 0) props[part.slice(0, eq).trim().toLowerCase()] = part.slice(eq + 1).trim();
  }
  return props;
}

function stripTimestamp(text) {
  return text.replace(/\r\n/g, '\n').split('\n').filter(line => !line.startsWith(TIMESTAMP_PREFIX)).join('\n');
}

function writeIfChanged(mdPath, content) {
  const exists = fs.existsSync(mdPath);
  if (exists && stripTimestamp(fs.readFileSync(mdPath, 'utf8')) === stripTimestamp(content)) return null;
  fs.writeFileSync(mdPath, content, 'utf8');
  return exists ? 'updated' : 'created';
}

// ==========================================
// Figma snapshot + diff
// ==========================================

function specsOf(node) {
  return {
    size: (px(node.width) && px(node.height)) ? `${px(node.width)} × ${px(node.height)}` : null,
    padding: padding(node),
    gap: px(node.itemSpacing),
    radius: px(node.cornerRadius),
    fontSize: px(node.fontSize),
    lineHeight: px(node.lineHeight),
    background: hex(node.backgroundColor),
    textColor: hex(node.textColor),
    border: hex(node.borderColor)
  };
}

const SPEC_LABELS = {
  size: 'Width × Height',
  padding: 'Padding',
  gap: 'Gap',
  radius: 'Corner radius',
  fontSize: 'Font size',
  lineHeight: 'Line height',
  background: 'Background',
  textColor: 'Text color',
  border: 'Border color',
  layoutMode: 'Layout mode'
};

function buildSnapshot(node) {
  const properties = {};
  const defs = node.componentPropertyDefinitions;
  if (defs && typeof defs === 'object') {
    for (const [key, def] of Object.entries(defs)) {
      properties[cleanPropName(key)] = {
        type: def?.type ?? null,
        defaultValue: def?.defaultValue === undefined ? null : String(def.defaultValue),
        options: Array.isArray(def?.variantOptions) ? def.variantOptions.map(String) : []
      };
    }
  }

  const variants = {};
  for (const child of Array.isArray(node.children) ? node.children : []) {
    if (child && child.name) variants[child.name] = specsOf(child);
  }

  return {
    name: node.name,
    description: typeof node.description === 'string' ? node.description.trim() : '',
    textContent: node.textContent ?? null,
    properties,
    base: { ...specsOf(node), layoutMode: node.layoutMode ?? null },
    variants
  };
}

function diffSpecs(prefix, before = {}, after = {}) {
  const changes = [];
  for (const key of new Set([...Object.keys(before), ...Object.keys(after)])) {
    const a = before[key] ?? null;
    const b = after[key] ?? null;
    if (a !== b) changes.push(`${prefix}${SPEC_LABELS[key] || key}: \`${a ?? '—'}\` → \`${b ?? '—'}\``);
  }
  return changes;
}

function diffSnapshots(prev, next) {
  const changes = [];
  if (prev.name !== next.name) changes.push(`Renamed: \`${prev.name}\` → \`${next.name}\``);
  if ((prev.description || '') !== (next.description || '')) {
    changes.push(`Description changed: "${prev.description || '—'}" → "${next.description || '—'}"`);
  }
  if ((prev.textContent ?? null) !== (next.textContent ?? null)) {
    changes.push(`Label text changed: "${prev.textContent ?? '—'}" → "${next.textContent ?? '—'}"`);
  }

  // Properties
  const pProps = prev.properties || {};
  const nProps = next.properties || {};
  for (const name of Object.keys(nProps)) {
    if (!pProps[name]) {
      changes.push(`Property added: \`${name}\` (${nProps[name].type})`);
      continue;
    }
    const a = pProps[name];
    const b = nProps[name];
    if (a.type !== b.type) changes.push(`Property \`${name}\` type: \`${a.type}\` → \`${b.type}\``);
    if (a.defaultValue !== b.defaultValue) {
      changes.push(`Property \`${name}\` default: \`${a.defaultValue ?? '—'}\` → \`${b.defaultValue ?? '—'}\``);
    }
    const added = b.options.filter(o => !a.options.includes(o));
    const removed = a.options.filter(o => !b.options.includes(o));
    if (added.length) changes.push(`Property \`${name}\` options added: ${added.map(o => `\`${o}\``).join(', ')}`);
    if (removed.length) changes.push(`Property \`${name}\` options removed: ${removed.map(o => `\`${o}\``).join(', ')}`);
  }
  for (const name of Object.keys(pProps)) {
    if (!nProps[name]) changes.push(`Property removed: \`${name}\``);
  }

  // Base specs
  changes.push(...diffSpecs('Base ', prev.base, next.base));

  // Variants
  const pVars = prev.variants || {};
  const nVars = next.variants || {};
  for (const name of Object.keys(nVars)) {
    if (!pVars[name]) changes.push(`Variant added: \`${name}\``);
    else changes.push(...diffSpecs(`Variant \`${name}\` — `, pVars[name], nVars[name]));
  }
  for (const name of Object.keys(pVars)) {
    if (!nVars[name]) changes.push(`Variant removed: \`${name}\``);
  }

  return changes;
}

// ==========================================
// Markdown sections
// ==========================================

function installationSection(pascalName, kebabName, usageProps = '', label = '') {
  const tag = label
    ? `<${pascalName}${usageProps}>${label}</${pascalName}>`
    : `<${pascalName}${usageProps} />`;
  return [
    '## Installation',
    '',
    '```bash',
    `npm install ${PACKAGE_NAME}@main`,
    '```',
    '',
    '```tsx',
    `import { ${pascalName} } from '${PACKAGE_NAME}';`,
    `import '${PACKAGE_NAME}/style.css';`,
    '',
    tag,
    '```',
    '',
    '```dart',
    `// Flutter: src/components/${kebabName}/${kebabName}.dart`,
    `UI${pascalName}()`,
    '```',
    ''
  ];
}

function codeFilesSection(kebabName) {
  return [
    '## Code files',
    '',
    '| File | Purpose |',
    '| --- | --- |',
    `| \`${kebabName}.tsx\` | React component |`,
    `| \`${kebabName}.types.ts\` | React prop types |`,
    `| \`${kebabName}.scss\` | Styles (token variables only) |`,
    `| \`${kebabName}.dart\` | Flutter widget |`,
    `| \`${kebabName}.md\` | This documentation |`,
    ''
  ];
}

function changelogSection(entry) {
  const lines = ['## Figma Changelog & Diff Status', ''];

  if (!entry || entry.status === 'local') {
    lines.push('> [!NOTE]');
    lines.push('> **Nothing changed** — this component has not been synced from Figma yet. Docs were generated from local code.');
    lines.push('');
    return lines;
  }

  if (entry.status === 'baseline') {
    lines.push('> [!NOTE]');
    lines.push(`> **Nothing to change** — first Figma sync captured the baseline snapshot (${entry.baselineAt}).`);
  } else if (entry.status === 'changed') {
    const latest = entry.history[0];
    lines.push('> [!IMPORTANT]');
    lines.push(`> **${latest.changes.length} change(s) detected** in the latest Figma sync (${latest.at}).`);
    lines.push('');
    lines.push('### Changes in latest sync');
    lines.push('');
    for (const change of latest.changes) lines.push(`- ${change}`);
  } else {
    lines.push('> [!TIP]');
    lines.push('> **Nothing changed** — the latest Figma sync matches the previous snapshot.');
  }
  lines.push('');

  const olderHistory = entry.status === 'changed' ? entry.history.slice(1) : entry.history;
  if (olderHistory.length > 0) {
    lines.push('### Previous changes');
    lines.push('');
    for (const item of olderHistory) {
      lines.push(`**${item.at}**`);
      lines.push('');
      for (const change of item.changes) lines.push(`- ${change}`);
      lines.push('');
    }
  }
  return lines;
}

function generateFigmaMarkdown(node, entry) {
  const { toPascalCase, toKebabCase } = naming();
  const pascalName = toPascalCase(node.name);
  const kebabName = toKebabCase(node.name);
  const snap = buildSnapshot(node);
  const lines = [GENERATED_MARKER, FIGMA_SOURCE_MARKER, ''];

  // 1. Overview
  lines.push(`# ${pascalName}`, '');
  lines.push(snap.description || '_No description set in Figma._', '');
  lines.push(`${TIMESTAMP_PREFIX}${new Date().toISOString()}`, '');
  lines.push('## Overview', '');
  lines.push('| Field | Value |', '| --- | --- |');
  lines.push(`| Figma name | ${md(node.name)} |`);
  lines.push(`| Node ID | ${md(node.id)} |`);
  lines.push(`| Node type | ${md(node.type)} |`);
  lines.push(`| Figma page | ${md(node.pageName)} |`);
  lines.push(`| Variants | ${Object.keys(snap.variants).length} |`);
  lines.push(`| Code folder | \`src/components/${kebabName}/\` |`);
  lines.push('');
  if (Array.isArray(node.documentationLinks) && node.documentationLinks.length > 0) {
    lines.push('**Documentation links**', '');
    for (const link of node.documentationLinks) {
      const uri = typeof link === 'string' ? link : link?.uri;
      if (uri) lines.push(`- ${uri}`);
    }
    lines.push('');
  }

  // 2. Text elements
  const textProps = Object.entries(snap.properties).filter(([, p]) => p.type === 'TEXT');
  lines.push('## Text elements', '');
  if (!snap.textContent && textProps.length === 0) {
    lines.push('_No text layers detected._', '');
  } else {
    lines.push('| Element | Default text |', '| --- | --- |');
    if (snap.textContent) lines.push(`| Primary label | ${md(snap.textContent)} |`);
    for (const [name, p] of textProps) lines.push(`| \`${name}\` (text property) | ${md(p.defaultValue)} |`);
    lines.push('');
  }

  // 3. Installation
  const variantProp = Object.entries(snap.properties).find(([n, p]) => p.type === 'VARIANT' && /style|variant/i.test(n));
  const sizeProp = Object.entries(snap.properties).find(([n, p]) => p.type === 'VARIANT' && /size/i.test(n));
  const usage = [
    variantProp ? ` variant="${String(variantProp[1].defaultValue || '').toLowerCase()}"` : '',
    sizeProp ? ` size="${String(sizeProp[1].defaultValue || '').toLowerCase()}"` : ''
  ].join('');
  lines.push(...installationSection(pascalName, kebabName, usage, snap.textContent || ''));

  // 4. Properties
  lines.push('## Properties', '');
  const propEntries = Object.entries(snap.properties).sort(([a], [b]) => a.localeCompare(b));
  if (propEntries.length === 0) {
    lines.push('_No component properties defined in Figma._', '');
  } else {
    lines.push('| Property | Type | Default | Options |', '| --- | --- | --- | --- |');
    for (const [name, p] of propEntries) {
      lines.push(`| \`${name}\` | ${md(p.type)} | ${md(p.defaultValue)} | ${md(p.options.join(', '))} |`);
    }
    lines.push('');
  }

  // 5. Size configurations (first variant per size value)
  const bySize = new Map();
  for (const child of Array.isArray(node.children) ? node.children : []) {
    const size = parseVariantName(child.name).size;
    if (size && !bySize.has(size)) bySize.set(size, specsOf(child));
  }
  if (bySize.size > 0) {
    lines.push('## Size configurations', '');
    lines.push('| Size | Width × Height | Padding (T R B L) | Gap | Radius | Font size |', '| --- | --- | --- | --- | --- | --- |');
    for (const [size, s] of bySize) {
      lines.push(`| ${md(size)} | ${md(s.size)} | ${md(s.padding)} | ${md(s.gap)} | ${md(s.radius)} | ${md(s.fontSize)} |`);
    }
    lines.push('');
  }

  // 6. Base specs
  lines.push('## Base specs', '');
  lines.push('| Spec | Value |', '| --- | --- |');
  for (const [key, value] of Object.entries(snap.base)) lines.push(`| ${SPEC_LABELS[key] || key} | ${md(value)} |`);
  lines.push('');

  // 7. Variants
  const variantNames = Object.keys(snap.variants).sort();
  if (variantNames.length > 0) {
    lines.push(`## Variants (${variantNames.length})`, '');
    lines.push('| Variant | W × H | Padding | Gap | Radius | Font size | Background | Text | Border |');
    lines.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
    for (const name of variantNames) {
      const v = snap.variants[name];
      lines.push(`| ${md(name)} | ${md(v.size)} | ${md(v.padding)} | ${md(v.gap)} | ${md(v.radius)} | ${md(v.fontSize)} | ${md(v.background)} | ${md(v.textColor)} | ${md(v.border)} |`);
    }
    lines.push('');
  }

  // 8. Figma Changelog & Diff Status
  lines.push(...changelogSection(entry));

  // 9. Code files
  lines.push(...codeFilesSection(kebabName));
  return lines.join('\n');
}

