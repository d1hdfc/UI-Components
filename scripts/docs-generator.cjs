// Public API: Figma sync
// ==========================================

/**
 * Create / update src/components/<kebab>/<kebab>.md from a Figma COMPONENT / COMPONENT_SET node,
 * diffing against the previous Figma snapshot. Returns
 * { result: 'created' | 'updated' | null, changes: string[] } — result is null when nothing was written.
 */
function writeComponentDocs(node) {
  if (!node || !node.name || String(node.name).includes('=')) return { result: null, changes: [] };
  const kebabName = naming().toKebabCase(node.name);
  const componentDir = path.join(COMPONENTS_DIR, kebabName);
  if (!fs.existsSync(componentDir)) return { result: null, changes: [] };

  const state = loadState();
  const now = new Date().toISOString();
  const snapshot = buildSnapshot(node);
  const prev = state[kebabName];
  let changes = [];
  let entry;

  if (!prev || !prev.snapshot) {
    entry = { status: 'baseline', baselineAt: now, history: [], snapshot };
  } else {
    changes = diffSnapshots(prev.snapshot, snapshot);
    if (changes.length > 0) {
      entry = {
        ...prev,
        status: 'changed',
        history: [{ at: now, changes }, ...(prev.history || [])].slice(0, HISTORY_LIMIT),
        snapshot
      };
    } else {
      // Payloads arriving within the burst window of the last change belong to the same Figma
      // edit (plugin documentchange + 2 s canvas poll + generator), so the status is kept.
      // After that, the status flips once to "unchanged" and the file stays stable.
      const lastChangeAt = Date.parse(prev.history?.[0]?.at || prev.baselineAt || 0) || 0;
      const inSameBurst = Date.now() - lastChangeAt < SYNC_BURST_MS;
      entry = { ...prev, status: inSameBurst ? prev.status : 'unchanged', snapshot };
    }
  }

  const stateChanged = !prev || changes.length > 0 || prev.status !== entry.status;
  if (stateChanged) {
    state[kebabName] = entry;
    saveState(state);
  }

  const mdPath = path.join(componentDir, `${kebabName}.md`);
  const result = writeIfChanged(mdPath, generateFigmaMarkdown(node, entry));
  return { result, changes };
}

// ==========================================
// Public API: Local baseline docs (no Figma data yet)
// ==========================================

function parseTypesFile(typesPath) {
  const source = fs.existsSync(typesPath) ? fs.readFileSync(typesPath, 'utf8') : '';
  const aliases = {};
  for (const m of source.matchAll(/export\s+type\s+(\w+)\s*=\s*([^;]+);/g)) aliases[m[1]] = m[2].trim();

  const props = [];
  const iface = source.match(/export\s+interface\s+\w+Props[^{]*\{([\s\S]*?)\n\}/);
  if (iface) {
    for (const m of iface[1].matchAll(/^\s*(\w+)(\?)?\s*:\s*([^;]+);/gm)) {
      const typeText = m[3].trim();
      props.push({ name: m[1], optional: Boolean(m[2]), type: typeText, resolved: aliases[typeText] || null });
    }
  }
  return { aliases, props };
}

function generateLocalMarkdown(kebabName) {
  const { toPascalCase } = naming();
  const pascalName = toPascalCase(kebabName);
  const { props } = parseTypesFile(path.join(COMPONENTS_DIR, kebabName, `${kebabName}.types.ts`));
  const lines = [GENERATED_MARKER, LOCAL_SOURCE_MARKER, ''];

  lines.push(`# ${pascalName}`, '');
  lines.push('_No Figma description yet — sync this component from Figma to populate it._', '');
  lines.push('## Overview', '');
  lines.push('| Field | Value |', '| --- | --- |');
  lines.push(`| Component | \`${pascalName}\` |`);
  lines.push(`| Code folder | \`src/components/${kebabName}/\` |`);
  lines.push('| Source | Local code (awaiting Figma sync) |');
  lines.push('');

  lines.push(...installationSection(pascalName, kebabName));

  lines.push('## Properties', '');
  if (props.length === 0) {
    lines.push('_Inherits native HTML attributes; no custom props declared._', '');
  } else {
    lines.push('| Prop | Type | Required | Options |', '| --- | --- | --- | --- |');
    for (const p of props) {
      lines.push(`| \`${p.name}\` | \`${md(p.type)}\` | ${p.optional ? 'No' : 'Yes'} | ${p.resolved ? `\`${md(p.resolved)}\`` : '—'} |`);
    }
    lines.push('');
  }

  const sizeProp = props.find(p => p.name === 'size' && p.resolved);
  if (sizeProp) {
    lines.push('## Size configurations', '');
    lines.push('| Size |', '| --- |');
    for (const size of sizeProp.resolved.split('|').map(s => s.trim().replace(/['"]/g, ''))) lines.push(`| ${md(size)} |`);
    lines.push('');
  }

  lines.push(...changelogSection({ status: 'local' }));
  lines.push(...codeFilesSection(kebabName));
  return lines.join('\n');
}

/**
 * Ensure every component folder has <kebab>.md. Creates local baseline docs only when the
 * file is missing, or refreshes existing local-sourced docs. Never overwrites Figma-sourced docs.
 */
function ensureLocalDocsForAll() {
  if (!fs.existsSync(COMPONENTS_DIR)) return 0;
  let written = 0;
  for (const entry of fs.readdirSync(COMPONENTS_DIR, { withFileTypes: true })) {
    if (!entry.isDirectory() || entry.name === 'assets') continue;
    const kebabName = entry.name;
    const dir = path.join(COMPONENTS_DIR, kebabName);
    if (!fs.existsSync(path.join(dir, `${kebabName}.tsx`))) continue;

    const mdPath = path.join(dir, `${kebabName}.md`);
    if (fs.existsSync(mdPath) && !fs.readFileSync(mdPath, 'utf8').includes(LOCAL_SOURCE_MARKER)) continue;
    if (writeIfChanged(mdPath, generateLocalMarkdown(kebabName))) written++;
  }
  if (written > 0) console.log(`[DocsSync] Generated ${written} local baseline .md file(s) in src/components/`);
  return written;
}

/** Drop stored snapshot/history for a deleted component. */
function forgetComponent(kebabName) {
  const state = loadState();
  if (state[kebabName]) {
    delete state[kebabName];
    saveState(state);
  }
}

