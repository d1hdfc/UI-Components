'use strict';

const fs = require('node:fs');
const path = require('node:path');

const COMPONENTS_DIR = path.join(process.cwd(), 'src', 'components');
const INDEX_FILE = path.join(COMPONENTS_DIR, 'index.ts');
const PAGES_DIR = path.join(process.cwd(), 'src', 'app', 'pages');
const GENERATED_MARKER = '// Generated by scripts/app-page-generator.cjs.';
const CUSTOM_PAGE_SLUGS = new Set(['button', 'text-area', 'text-field', 'header']);
const PROTECTED_PAGE_DIRS = new Set([
  'ButtonPage',
  'TextAreaPage',
  'TextFieldPage',
  'HeaderPage',
  'SidebarPage',
  'FigmaComponentsPage',
  'ComponentPage'
]);

function toPageName(slug) {
  const parts = slug
    .replace(/^\d+[-_\s]+/, '')
    .split(/[-_\s]+/)
    .filter(Boolean)
    .map((part) => `${part.charAt(0).toUpperCase()}${part.slice(1)}`);
  if (parts.length > 0 && /^\d/.test(parts[0])) {
    parts[0] = `Comp${parts[0]}`;
  }
  return parts.join('');
}

function writeFileIfChanged(filePath, content) {
  if (fs.existsSync(filePath)) {
    const existing = fs.readFileSync(filePath, 'utf8');
    if (existing === content) return false;
  }
  fs.writeFileSync(filePath, content, 'utf8');
  return true;
}

function getPageTsxSource(slug, pageName) {
  const fullPageName = `${pageName}Page`;
  return `${GENERATED_MARKER}
import { componentDocumentation } from '../ComponentPage/componentRegistry';
import { ComponentPage } from '../ComponentPage/ComponentPage';
import './${fullPageName}.scss';

export const componentSlug = ${JSON.stringify(slug)};

export function ${fullPageName}() {
  const component = componentDocumentation.find((entry) => entry.slug === componentSlug);
  return component ? <ComponentPage component={component} /> : null;
}

export default ${fullPageName};
`;
}

function getPageTsSource(pageName) {
  const fullPageName = `${pageName}Page`;
  return `${GENERATED_MARKER}
export { ${fullPageName}, default, componentSlug } from './${fullPageName}.tsx';
`;
}

function getPageScssSource(slug) {
  return `${GENERATED_MARKER}
.docs-page-${slug} {
  display: block;
  color: var(--text-strong);
  font-family: var(--font-family-inter);
}
`;
}

function cleanInvalidDigitPrefixedComponents() {
  if (!fs.existsSync(COMPONENTS_DIR)) return;

  for (const entry of fs.readdirSync(COMPONENTS_DIR, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    if (/^\d+-/.test(entry.name)) {
      const stripped = entry.name.replace(/^\d+-/, '');
      if (fs.existsSync(path.join(COMPONENTS_DIR, stripped))) {
        fs.rmSync(path.join(COMPONENTS_DIR, entry.name), { recursive: true, force: true });
      }
    }
  }

  if (fs.existsSync(INDEX_FILE)) {
    const content = fs.readFileSync(INDEX_FILE, 'utf8');
    const cleanedLines = content.split('\n').filter((line) => {
      return !/export\s+(?:type\s+)?\{\s*\d/.test(line);
    });
    if (cleanedLines.length !== content.split('\n').length) {
      fs.writeFileSync(INDEX_FILE, cleanedLines.join('\n'), 'utf8');
    }
  }
}

function normalizeCustomPageDirs() {
  if (!fs.existsSync(PAGES_DIR)) return;
  for (const dirName of ['ButtonPage', 'TextAreaPage', 'TextFieldPage', 'HeaderPage', 'SidebarPage', 'FigmaComponentsPage']) {
    const dirPath = path.join(PAGES_DIR, dirName);
    if (!fs.existsSync(dirPath)) continue;

    // Remove legacy index.ts or stray ComponentDocsPage.tsx
    const legacyIndex = path.join(dirPath, 'index.ts');
    if (fs.existsSync(legacyIndex)) fs.rmSync(legacyIndex, { force: true });
    const strayDocs = path.join(dirPath, 'ComponentDocsPage.tsx');
    if (fs.existsSync(strayDocs)) fs.rmSync(strayDocs, { force: true });

    // Ensure <PageName>.ts exists
    const tsBarrelPath = path.join(dirPath, `${dirName}.ts`);
    writeFileIfChanged(tsBarrelPath, `export { ${dirName} } from './${dirName}.tsx';\n`);
  }
}

function syncAppComponentPages() {
  if (!fs.existsSync(COMPONENTS_DIR)) return;

  cleanInvalidDigitPrefixedComponents();
  normalizeCustomPageDirs();

  const validPageDirs = new Set(PROTECTED_PAGE_DIRS);
  const entries = fs.readdirSync(COMPONENTS_DIR, { withFileTypes: true });

  for (const entry of entries) {
    if (!entry.isDirectory() || entry.name === 'assets' || CUSTOM_PAGE_SLUGS.has(entry.name)) continue;

    const componentDir = path.join(COMPONENTS_DIR, entry.name);
    const hasReactComponent = fs.readdirSync(componentDir)
      .some((file) => file.endsWith('.tsx') && !file.endsWith('.test.tsx'));
    if (!hasReactComponent) continue;

    const pageName = toPageName(entry.name);
    if (!pageName) continue;

    const fullPageName = `${pageName}Page`;
    const pageDir = path.join(PAGES_DIR, fullPageName);
    validPageDirs.add(fullPageName);

    fs.mkdirSync(pageDir, { recursive: true });

    const tsxPath = path.join(pageDir, `${fullPageName}.tsx`);
    const tsPath = path.join(pageDir, `${fullPageName}.ts`);
    const scssPath = path.join(pageDir, `${fullPageName}.scss`);

    // Remove legacy ComponentDocsPage.tsx or index.ts if present
    for (const file of fs.readdirSync(pageDir)) {
      if (file !== `${fullPageName}.tsx` && file !== `${fullPageName}.ts` && file !== `${fullPageName}.scss`) {
        fs.rmSync(path.join(pageDir, file), { recursive: true, force: true });
      }
    }

    writeFileIfChanged(tsxPath, getPageTsxSource(entry.name, pageName));
    writeFileIfChanged(tsPath, getPageTsSource(pageName));
    writeFileIfChanged(scssPath, getPageScssSource(entry.name));
  }

  if (!fs.existsSync(PAGES_DIR)) return;

  // Clean up stale page directories for deleted components
  for (const entry of fs.readdirSync(PAGES_DIR, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    if (!validPageDirs.has(entry.name)) {
      fs.rmSync(path.join(PAGES_DIR, entry.name), { recursive: true, force: true });
    }
  }
}

if (require.main === module) {
  syncAppComponentPages();
}

module.exports = { syncAppComponentPages, toPageName };
