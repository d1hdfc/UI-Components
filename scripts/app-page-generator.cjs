'use strict';

const fs = require('node:fs');
const path = require('node:path');

const COMPONENTS_DIR = path.join(process.cwd(), 'src', 'components');
const PAGES_DIR = path.join(process.cwd(), 'src', 'app', 'pages');
const GENERATED_MARKER = '// Generated by scripts/app-page-generator.cjs.';
const CUSTOM_PAGE_SLUGS = new Set(['button', 'text-area', 'text-field']);

function toPageName(slug) {
  return slug
    .split(/[-_\s]+/)
    .filter(Boolean)
    .map((part) => `${part.charAt(0).toUpperCase()}${part.slice(1)}`)
    .join('');
}

function getPageSource(slug, pageName) {
  return `${GENERATED_MARKER}
import { componentDocumentation } from '../ComponentPage/componentRegistry';
import { ComponentPage } from '../ComponentPage/ComponentPage';

export const componentSlug = ${JSON.stringify(slug)};

export default function ${pageName}ComponentDocsPage() {
  const component = componentDocumentation.find((entry) => entry.slug === componentSlug);
  return component ? <ComponentPage component={component} /> : null;
}
`;
}

function syncAppComponentPages() {
  if (!fs.existsSync(COMPONENTS_DIR)) return;

  const pageFiles = new Set();
  const entries = fs.readdirSync(COMPONENTS_DIR, { withFileTypes: true });

  for (const entry of entries) {
    if (!entry.isDirectory() || entry.name === 'assets' || CUSTOM_PAGE_SLUGS.has(entry.name)) continue;

    const componentDir = path.join(COMPONENTS_DIR, entry.name);
    const hasReactComponent = fs.readdirSync(componentDir)
      .some((file) => file.endsWith('.tsx') && !file.endsWith('.test.tsx'));
    if (!hasReactComponent) continue;

    const pageName = toPageName(entry.name);
    if (!pageName) continue;

    const pageDir = path.join(PAGES_DIR, `${pageName}Page`);
    const pagePath = path.join(pageDir, 'ComponentDocsPage.tsx');
    pageFiles.add(pagePath);

    fs.mkdirSync(pageDir, { recursive: true });
    if (fs.existsSync(pagePath)) {
      const currentSource = fs.readFileSync(pagePath, 'utf8');
      if (!currentSource.startsWith(GENERATED_MARKER)) continue;
    }

    fs.writeFileSync(pagePath, getPageSource(entry.name, pageName), 'utf8');
  }

  if (!fs.existsSync(PAGES_DIR)) return;

  for (const entry of fs.readdirSync(PAGES_DIR, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const pagePath = path.join(PAGES_DIR, entry.name, 'ComponentDocsPage.tsx');
    if (!fs.existsSync(pagePath) || pageFiles.has(pagePath)) continue;

    const source = fs.readFileSync(pagePath, 'utf8');
    if (!source.startsWith(GENERATED_MARKER)) continue;

    fs.unlinkSync(pagePath);
    try {
      fs.rmdirSync(path.dirname(pagePath));
    } catch (error) {
      if (error.code !== 'ENOTEMPTY' && error.code !== 'ENOENT') throw error;
    }
  }
}

if (require.main === module) {
  syncAppComponentPages();
}

module.exports = { syncAppComponentPages };
